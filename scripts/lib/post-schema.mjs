// Front-matter and required-section validation for posts. Pure: no file access.
import { CODE_LANGS } from '../viewers.mjs';

export const TEXT_LICENSES = ['CC-BY-4.0', 'CC-BY-SA-4.0', 'CC0-1.0'];
export const CODE_LICENSES = ['MIT', 'Apache-2.0', 'BSD-3-Clause', 'CC0-1.0'];
export const BOILERPLATE_CHECKS = ['verified', 'i verified the results', 'i checked the results', 'looks good', 'done', 'n/a', 'yes'];

const USER_RE = /^[a-z\d](?:[a-z\d-]{0,38})$/i;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const isStr = (s) => typeof s === 'string' && s.trim() !== '';
// gray-matter parses bare YAML dates into Date objects
const dayOf = (d) => (d instanceof Date ? (isNaN(d) ? '' : d.toISOString().slice(0, 10)) : String(d ?? ''));

// ATX "## " headings outside fenced code blocks
export function h2s(markdown) {
  const out = [];
  let fence = null;
  for (const line of String(markdown).split(/\r?\n/)) {
    const f = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (f) {
      if (!fence) fence = f[1][0].repeat(f[1].length);
      else if (f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
      continue;
    }
    if (fence) continue;
    const m = line.match(/^ {0,3}##[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$/);
    if (m) out.push(m[1].trim());
  }
  return out;
}

export function validatePost({ fm = {}, markdown = '', folderUser, files = [] }) {
  const e = [];
  const authors = fm.authors;
  const okAuthors = Array.isArray(authors) && authors.length > 0 && authors.every((a) => typeof a === 'string' && USER_RE.test(a));
  if (!okAuthors) e.push('authors: must be a non-empty list of GitHub usernames');
  else if (authors[0] !== folderUser) e.push(`authors: first author must be the folder owner "${folderUser}"`);

  if (!Array.isArray(fm.ai) || fm.ai.length === 0) e.push('ai: must be a non-empty list of { name, model, role }');
  else fm.ai.forEach((a, i) => {
    for (const k of ['name', 'model', 'role']) if (!isStr(a?.[k])) e.push(`ai[${i}].${k}: must be a non-empty string`);
  });

  if (!isStr(fm.contribution) || fm.contribution.trim().length < 40) e.push('contribution: required, at least 40 characters describing who did what');
  if (!TEXT_LICENSES.includes(fm.license)) e.push(`license: must be one of ${TEXT_LICENSES.join(', ')}`);
  if (!CODE_LICENSES.includes(fm.code_license)) e.push(`code_license: must be one of ${CODE_LICENSES.join(', ')}`);

  const v = fm.author_verification;
  if (!v || typeof v !== 'object') e.push('author_verification: required ({ verified, by, date, checked })');
  else {
    if (v.verified !== true) e.push('author_verification.verified: must be true');
    if (!okAuthors || !authors.includes(v.by)) e.push('author_verification.by: must be one of the authors');
    const d = dayOf(v.date);
    if (!DATE_RE.test(d) || isNaN(new Date(d))) e.push('author_verification.date: must be a YYYY-MM-DD date');
    else if (d > new Date().toISOString().slice(0, 10)) e.push('author_verification.date: must not be in the future');
    const c = typeof v.checked === 'string' ? v.checked.trim() : '';
    if (c.length < 40) e.push('author_verification.checked: say specifically what you checked (at least 40 characters)');
    else if (/TODO/.test(c)) e.push('author_verification.checked: must not contain TODO');
    else if (BOILERPLATE_CHECKS.includes(c.toLowerCase())) e.push('author_verification.checked: boilerplate text is not accepted');
  }

  // sections
  const heads = h2s(markdown);
  for (const h of heads) {
    if (/^(reproduce|references|specs|author verification)/i.test(h)) e.push(`section "${h}": generated by the build, do not write it by hand`);
  }
  let from = 0;
  for (const [re, name] of [[/^(the )?question/i, 'The question'], [/^(what we did|experiment|method)/i, 'What we did'], [/^results/i, 'Results']]) {
    const i = heads.findIndex((h, j) => j >= from && re.test(h));
    if (i >= 0) { from = i + 1; continue; }
    e.push(heads.some((h) => re.test(h)) ? `section "${name}": out of order (required order: The question, What we did, Results)` : `section "${name}": missing required H2`);
    break;
  }

  // files
  const ext = (f) => (f.includes('.') ? f.slice(f.lastIndexOf('.')).toLowerCase() : '');
  if (!files.some((f) => CODE_LANGS[ext(f)] && !/^(refs|run)\.json$/.test(f))) e.push('code: the post folder must contain at least one code file');
  const links = fm.chat_links;
  if (links !== undefined && !(Array.isArray(links) && links.every((u) => typeof u === 'string' && /^https:\/\/\S+$/.test(u)))) e.push('chat_links: must be a list of https URLs');
  const hasLinks = Array.isArray(links) && links.length > 0;
  if (!hasLinks && !files.some((f) => /^chat\/[^/]+\.md$/i.test(f))) e.push('chat: add a chat/*.md excerpt or a non-empty chat_links list');
  return e;
}
